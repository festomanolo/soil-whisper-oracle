export const mboleaStrings = { en, sw };
export type MboleaStrings = Strings;

export function useMboleaT(): MboleaStrings {
  const { lang } = useLanguage();
  return mboleaStrings[lang] ?? sw;
}

/** Replaces {key} placeholders. */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

export const tsh = (n: number) => `TSh ${Math.round(n).toLocaleString('en-US')}`;
export const num = (n: number, digits = 0) =>
  n.toLocaleString('en-US', { maximumFractionDigits: digits, minimumFractionDigits: 0 });
